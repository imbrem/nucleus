/// A path a `links` package publishes to its dependents' build scripts.
///
/// Cargo hands a build script `DEP_<LINKS>_<KEY>` for every `cargo::metadata=`
/// line printed by the build script of a direct dependency declaring `links`.
/// Buck's prelude keeps only the directives it can turn into rustc arguments —
/// `--cfg`, `-l`, `-L`, `--env-set` — and discards the rest, so nothing
/// propagates. There is no way to recover a value computed at build time, so
/// the ones this workspace consumes are restated here as Buck labels.
///
/// A missing entry is not silent: the dependent build script fails on the
/// absent variable, the way cas-shell's does, rather than compiling against
/// the wrong header.
struct LinksMetadata {
    /// The `links` value of the package that publishes it.
    links: &'static str,
    /// The `DEP_<LINKS>_<KEY>` suffix, spelled as cargo spells it.
    key: &'static str,
    /// Where it points, relative to the publishing crate's own source tree.
    path: &'static str,
}

const LINKS_METADATA: &[LinksMetadata] = &[LinksMetadata {
    links: "sqlite3",
    key: "INCLUDE",
    // `libsqlite3-sys` prints `cargo:include=$CARGO_MANIFEST_DIR/sqlite3` from
    // its bundled path: the amalgamation directory inside its own crate, which
    // is where the `sqlite3.h` matching the linked library lives.
    path: "sqlite3",
}];

/// A workspace package's `build.rs`, as the pair of rules Buck wants.
///
/// One per package, not one per target: cargo runs a build script once and
/// every target in the package sees the same `OUT_DIR` and the same flags.
#[derive(Serialize)]
struct WorkspaceBuildscript {
    /// The label prefix shared by `-build-script-build` and
    /// `-build-script-run`, which is also what targets reference.
    name: String,
    package_name: String,
    version: String,
    crate_root: String,
    edition: String,
    features: Vec<String>,
    named_deps: Vec<(String, String)>,
    /// What compiling `build.rs` sees, for the `env!` it reads at compile time.
    env: Vec<(String, String)>,
    /// What running it sees: the same plus `DEP_<LINKS>_<KEY>`.
    ///
    /// Kept off the compile rule because those are `$(location)` on a
    /// dependency's source archive, and the compile rule is re-configured once
    /// per Reindeer platform. Putting them there would fetch and configure
    /// that archive once per platform for a variable no compilation reads.
    run_env: Vec<(String, String)>,
}

